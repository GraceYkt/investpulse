def curated_item(rank, i, c):
    kind_map = {'deposit': 'Вклад', 'fund': 'Фонд ден. рынка', 'stock': 'Акция'}
    asset = 'Золото' if 'золот' in c['name'].lower() or 'TGLD' in c['name'] or 'GLDRUB' in c['name'] else kind_map[c['kind']]
    if c['kind'] == 'stock' and 'золот' in c['desc'].lower():
        asset = 'Золотодобытчик'
    name_l = c['name'].lower()
    texts = None
    for r, kw, key in TEXT_RULES:
        if r == rank and kw in name_l:
            texts = CURATED_TEXTS.get(key)
            if texts:
                break
    if texts is None:
        texts = dict(
            why='Входит в топ-5 направления по совокупности доходности, надёжности и ликвидности.',
            now=c['desc'],
            down='Ставка ↓: сценарий описан в деталях идеи.',
            flat='Ставка без изменений: базовый сценарий.',
            up='Ставка ↑: сценарий описан в деталях идеи.',
        )
    sens = {'deposit': 'низкая', 'fund': 'низкая', 'stock': 'высокая'}.get(c['kind'], 'средняя')
    if c['kind'] == 'stock' and asset == 'Золото':
        sens = 'средняя'
    return {
        'key': f'{rank}:{i}',
        'rank': rank,
        'ideaTitle': IDEA_TITLES[rank],
        'kind': c['kind'],
        'assetType': asset,
        'name': c['name'],
        'desc': c['desc'],
        'why': texts['why'],
        'now': texts['now'],
        'scenDown': texts['down'],
        'scenFlat': texts['flat'],
        'scenUp': texts['up'],
        'sensitivity': sens,
        'buyUrl': c['buyUrl'],
    }


def main():
    with open(os.path.join(ROOT, 'invest-app/src/data/idea-picks.json'), encoding='utf-8') as f:
        picks = json.load(f)
    as_of = picks.get('asOf', '2026-10-22')
    items = []
    for rank_s in sorted((k for k in picks.keys() if k != 'asOf'), key=lambda k: int(k)):
        rank = int(rank_s)
        for i, p in enumerate(picks[rank_s]):
            if 'yield' in p:
                items.append(bond_item(rank, i, p))
            else:
                items.append(curated_item(rank, i, p))
    missing = [it['name'] for it in items if it['why'].startswith('Входит в топ-5')]
    out = {'asOf': as_of, 'keyRate': KEY_RATE, 'items': items}
    path = os.path.join(ROOT, 'invest-app/src/data/pick-analytics.json')
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    print(f'items: {len(items)} -> {path}')
    if missing:
        print('тексты-заглушки:', missing)


if __name__ == '__main__':
    main()
